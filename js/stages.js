  // ── Stage 16-35 — 程序化生成（固定 seed，難度遞增）──
  function generate(seed) {
    const g = Array.from({ length: 13 }, () => Array(13).fill('.'));
    let s = (seed * 2654435761) >>> 0;
    const rnd = () => {
      s ^= s << 13; s >>>= 0;
      s ^= s >>> 17;
      s ^= s << 5;  s >>>= 0;
      return s / 4294967296;
    };
    const diff = (seed - 16) / 19; // 0 → 1

    for (let r = 0; r < 11; r++) {
      for (let c = 0; c < 13; c++) {
        // 出生通道淨空
        if (r <= 1 && (c <= 1 || c === 6 || c >= 11)) continue;
        if (r >= 10 && (c === 4 || c === 8)) continue; // 玩家出生
        const v = rnd();
        if      (v < 0.16 + diff * 0.06) g[r][c] = '#';
        else if (v < 0.20 + diff * 0.10) g[r][c] = 'S';
        else if (v < 0.24 && seed > 20)  g[r][c] = '~';
        else if (v < 0.28 && seed > 24)  g[r][c] = 'F';
        else if (v < 0.32 && seed > 28)  g[r][c] = 'I';
      }
    }
    // 左右鏡像，關卡更均衡
    for (let r = 0; r < 11; r++) {
      for (let c = 0; c < 6; c++) {
        if (rnd() < 0.6) g[r][12 - c] = g[r][c];
      }
    }
    g[12][6] = 'B';
    return g.map(line => line.join(''));
  }

  const generated = [];
  for (let i = 16; i <= 35; i++) generated.push(generate(i));

  return hand.concat(generated);
